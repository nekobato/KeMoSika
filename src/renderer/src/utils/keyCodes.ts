/** Converts a DOM physical-key code into the visualizer's stored input code. */
export const keyboardCodeToInputCode = (code: string): string => {
  const letter = /^Key([A-Z])$/.exec(code)?.[1];
  if (letter) return letter;

  const digit = /^Digit([0-9])$/.exec(code)?.[1];
  if (digit) return digit;

  const numpadDigit = /^Numpad([0-9])$/.exec(code)?.[1];
  if (numpadDigit) return `numpad${numpadDigit}`;

  if (/^F(?:[1-9]|1[0-9]|2[0-4])$/.test(code)) {
    return code.toLowerCase();
  }

  return domKeyboardCodeMap[code] ?? "";
};

